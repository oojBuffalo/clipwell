import AppKit
import Combine
import OSLog

struct ClipEntry: Codable, Hashable, Identifiable {
    let id: UUID
    let text: String
    let createdAt: Date
    var isPinned: Bool
}

@MainActor
final class HistoryStore: ObservableObject {
    @Published private(set) var entries: [ClipEntry] = []
    @Published private(set) var isPaused = false

    private struct Snapshot: Codable {
        let entries: [ClipEntry]
        let isPaused: Bool
    }

    private static let unpinnedLimit = 100
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("de.petermaurer.TransientPasteboardType"),
        .init("com.agilebits.onepassword"),
    ]
    private let logger = Logger(subsystem: "app.clipwell.Clipwell", category: "History")
    private let pasteboard: NSPasteboard
    private let fileURL: URL
    private var lastChangeCount = 0
    private var timer: Timer?

    convenience init() {
        let directory = URL.applicationSupportDirectory.appending(path: "Clipwell", directoryHint: .isDirectory)
        self.init(pasteboard: .general, storageDirectory: directory)
    }

    init(pasteboard: NSPasteboard, storageDirectory: URL) {
        self.pasteboard = pasteboard
        self.fileURL = storageDirectory.appending(path: "history.json")
        do {
            let snapshot = try JSONDecoder().decode(Snapshot.self, from: Data(contentsOf: fileURL))
            entries = snapshot.entries
            isPaused = snapshot.isPaused
        } catch let error as CocoaError where error.code == .fileReadNoSuchFile {
            // No history has been saved yet.
        } catch {
            logger.error("Could not load clipboard history: \(error.localizedDescription, privacy: .private)")
        }
    }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.05
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func poll() {
        guard timer != nil else { return }
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        guard !isPaused, let types = pasteboard.types, types.contains(.string),
              Self.ignoredTypes.isDisjoint(with: types),
              let text = pasteboard.string(forType: .string), !text.isEmpty,
              pasteboard.changeCount == changeCount else { return }

        var updated = entries
        let existingIndex = updated.firstIndex { $0.text == text }
        let existing = existingIndex.map { updated.remove(at: $0) }
        let latest = ClipEntry(id: existing?.id ?? UUID(), text: text, createdAt: Date(),
                               isPinned: existing?.isPinned ?? false)
        updated.insert(latest, at: 0)
        entries = withinHistoryLimit(updated)
        save()
    }

    @discardableResult
    func copy(_ entry: ClipEntry) -> Bool {
        poll()
        lastChangeCount = pasteboard.clearContents()
        return pasteboard.setString(entry.text, forType: .string)
    }

    func togglePin(_ entry: ClipEntry) {
        guard let index = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        var updated = entries
        updated[index].isPinned.toggle()
        entries = withinHistoryLimit(updated)
        save()
    }

    func remove(_ entry: ClipEntry) {
        entries.removeAll { $0.id == entry.id }
        save()
    }

    func togglePause() {
        lastChangeCount = pasteboard.changeCount
        isPaused.toggle()
        save()
    }

    func clearUnpinned() {
        entries.removeAll { !$0.isPinned }
        save()
    }

    private func withinHistoryLimit(_ updated: [ClipEntry]) -> [ClipEntry] {
        guard updated.count > Self.unpinnedLimit else { return updated }
        var unpinnedCount = 0
        return updated.filter { entry in
            guard !entry.isPinned else { return true }
            unpinnedCount += 1
            return unpinnedCount <= Self.unpinnedLimit
        }
    }

    private func save() {
        let manager = FileManager.default
        do {
            try manager.createDirectory(at: fileURL.deletingLastPathComponent(),
                                        withIntermediateDirectories: true,
                                        attributes: [.posixPermissions: 0o700])
            let data = try JSONEncoder().encode(Snapshot(entries: entries, isPaused: isPaused))
            try data.write(to: fileURL, options: .atomic)
            try manager.setAttributes([.posixPermissions: 0o600], ofItemAtPath: fileURL.path)
        } catch {
            logger.error("Could not save clipboard history: \(error.localizedDescription, privacy: .private)")
        }
    }
}
