import AppKit
import XCTest
@testable import Clipwell

@MainActor
final class HistoryStoreTests: XCTestCase {
    private func withStore(_ test: (HistoryStore, NSPasteboard, URL) async throws -> Void) async rethrows {
        let board = NSPasteboard.withUniqueName()
        let directory = FileManager.default.temporaryDirectory.appending(path: UUID().uuidString)
        let store = HistoryStore(pasteboard: board, storageDirectory: directory)
        defer {
            store.stop()
            board.releaseGlobally()
            try? FileManager.default.removeItem(at: directory)
        }
        try await test(store, board, directory)
    }

    private func write(_ text: String, to board: NSPasteboard) {
        board.clearContents()
        XCTAssertTrue(board.setString(text, forType: .string))
    }

    func testMonitorAutomaticallyCapturesNewText() async {
        await withStore { store, board, _ in
            let captured = expectation(description: "Timer captures text")
            let observation = store.$entries.sink { entries in
                if entries.first?.text == "automatic" { captured.fulfill() }
            }
            store.start()
            write("automatic", to: board)
            await fulfillment(of: [captured], timeout: 4)
            observation.cancel()
        }
    }

    func testStartsWithTheNextCopyAndSkipsContentFromWhilePausedOrStopped() async {
        await withStore { store, board, _ in
            write("before start", to: board)
            store.start()
            store.poll()
            XCTAssertTrue(store.entries.isEmpty)
            write("first copy", to: board)
            store.poll()

            store.togglePause()
            write("paused", to: board)
            store.poll()
            write("immediately before resuming", to: board)
            store.togglePause()
            store.poll()
            store.stop()
            write("stopped", to: board)
            store.start()
            store.poll()
            write("after restart", to: board)
            store.poll()
            XCTAssertEqual(store.entries.map(\.text), ["after restart", "first copy"])
        }
    }

    func testSensitiveOrNontextCopiesAreSkipped() async {
        await withStore { store, board, _ in
            store.start()
            for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                           "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
                let privateItem = NSPasteboardItem()
                privateItem.setString("secret", forType: .string)
                privateItem.setData(Data(), forType: .init(marker))
                board.clearContents()
                XCTAssertTrue(board.writeObjects([privateItem]))
                store.poll()
            }
            board.clearContents()
            XCTAssertTrue(board.setData(Data([0x42]), forType: .init("com.example.binary")))
            store.poll()
            write("", to: board)
            store.poll()
            XCTAssertTrue(store.entries.isEmpty)
        }
    }

    func testRecallPreservesTheTextAndDoesNotCreateANewCapture() async throws {
        try await withStore { store, board, _ in
            store.start()
            let text = "  Résumé 🗂\n\tsecond line  "
            write(text, to: board)
            store.poll()
            let first = try XCTUnwrap(store.entries.first)
            store.togglePin(first)
            write("later", to: board)
            store.poll()
            let snapshot = store.entries
            XCTAssertTrue(store.copy(first))
            XCTAssertEqual(board.string(forType: .string), text)
            store.poll()
            XCTAssertEqual(store.entries, snapshot)

            write(text, to: board)
            store.poll()
            XCTAssertEqual(store.entries.map(\.text), [text, "later"])
            XCTAssertEqual(store.entries.first?.id, first.id)
            XCTAssertEqual(store.entries.first?.isPinned, true)
        }
    }

    func testPinningDeletionAndPauseSurviveRelaunch() async throws {
        try await withStore { store, board, directory in
            store.start()
            write("keep", to: board)
            store.poll()
            let kept = try XCTUnwrap(store.entries.first)
            store.togglePin(kept)
            write("discard", to: board)
            store.poll()
            store.clearUnpinned()
            store.togglePause()
            store.stop()

            let restored = HistoryStore(pasteboard: board, storageDirectory: directory)
            XCTAssertTrue(restored.isPaused)
            XCTAssertEqual(restored.entries.map(\.id), [kept.id])
            XCTAssertEqual(restored.entries.first?.isPinned, true)
            restored.remove(kept)
            XCTAssertTrue(HistoryStore(pasteboard: board, storageDirectory: directory).entries.isEmpty)
            let permissions = try FileManager.default.attributesOfItem(atPath: directory.path)[.posixPermissions]
            XCTAssertEqual(permissions as? Int, 0o700)
        }
    }

    func testRecallKeepsAnExternalCopyThatArrivedBetweenPolls() async throws {
        try await withStore { store, board, _ in
            store.start()
            write("previous", to: board)
            store.poll()
            let previous = try XCTUnwrap(store.entries.first)
            write("just copied", to: board)

            XCTAssertTrue(store.copy(previous))
            XCTAssertEqual(board.string(forType: .string), "previous")
            store.poll()
            XCTAssertEqual(store.entries.map(\.text), ["just copied", "previous"])
        }
    }

    func testOldestUnpinnedItemsExpireWithoutEvictingPins() async throws {
        try await withStore { store, board, _ in
            store.start()
            write("pin", to: board)
            store.poll()
            let pin = try XCTUnwrap(store.entries.first)
            store.togglePin(pin)
            for i in 0...101 {
                write(String(i), to: board)
                store.poll()
            }
            XCTAssertEqual(store.entries.count, 101)
            XCTAssertEqual(store.entries.first?.text, "101")
            XCTAssertEqual(store.entries.suffix(2).map(\.text), ["2", "pin"])
            store.togglePin(pin)
            XCTAssertEqual(store.entries.count, 100)
            XCTAssertEqual(store.entries.last?.text, "2")
        }
    }
}
